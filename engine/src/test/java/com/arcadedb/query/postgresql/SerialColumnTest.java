package com.arcadedb.query.postgresql;

import com.arcadedb.TestHelper;
import com.arcadedb.query.postgresql.catalog.Sequences;
import com.arcadedb.query.sql.executor.Result;
import com.arcadedb.query.sql.executor.ResultSet;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.CopyOnWriteArrayList;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * {@code serial} and identity columns (fork issue #221): the numbers they give, in every language, and the SQLSTATE of each
 * refusal. The comparison with PostgreSQL 18 is {@code PostgreSQLSerialColumnTest} of the {@code postgresw} module.
 */
class SerialColumnTest extends TestHelper {
  @ParameterizedTest
  @CsvSource(delimiter = ';', value = { "serial; 2147483647", "serial4; 2147483647", "bigserial; 9223372036854775807",
      "serial8; 9223372036854775807", "smallserial; 32767", "SERIAL NOT NULL; 2147483647",
      "int GENERATED ALWAYS AS IDENTITY; 2147483647", "bigint GENERATED BY DEFAULT AS IDENTITY; 9223372036854775807",
      "smallint generated by default as identity (start with 1 increment by 1 no cycle); 32767" })
  void aColumnThatIsLeftOutTakesTheNextNumber(final String type, final long maximum) {
    run("CREATE TABLE t (id " + type + " PRIMARY KEY, v text)");

    assertThat(numbers("INSERT INTO t (v) VALUES ('a'), ('b') RETURNING id")).containsExactly(1L, 2L);
    assertThat(numbers("INSERT INTO t (id, v) VALUES (DEFAULT, 'c') RETURNING id")).containsExactly(3L);
    assertThat(numbers("INSERT INTO t VALUES (DEFAULT, 'd') RETURNING id")).containsExactly(4L);
    assertThat(numbers("UPDATE t SET id = DEFAULT WHERE v = 'a' RETURNING id")).containsExactly(5L);
    assertThat(numbers("SELECT id FROM t ORDER BY id")).containsExactly(2L, 3L, 4L, 5L);
    assertState("INSERT INTO t (id, v) VALUES (NULL, 'n')", type.contains("ALWAYS") ? "428C9" : "23502");

    // the counter of the column ends at the largest value of its type
    database.transaction(
        () -> database.command("sql", "UPDATE " + Sequences.TYPE_NAME + " SET `last` = " + (maximum - 1)).close());
    assertThat(numbers("INSERT INTO t (v) VALUES ('last') RETURNING id")).containsExactly(maximum);
    assertState("INSERT INTO t (v) VALUES ('beyond')", "2200H");
  }

  @Test
  void sqlAndOpenCypherFillAColumnThatTheyLeaveOut() {
    run("CREATE TABLE t (id serial PRIMARY KEY, n bigint GENERATED ALWAYS AS IDENTITY, v text)");

    database.transaction(() -> database.command("sql", "INSERT INTO t SET v = 'sql'").close());
    database.transaction(() -> database.command("sql", "INSERT INTO t CONTENT {\"v\": \"content\"}").close());
    database.transaction(() -> database.command("opencypher", "CREATE (:t {v: 'cypher'})").close());
    database.transaction(() -> database.newVertex("t").set("v", "java").save());
    run("INSERT INTO t (v) VALUES ('postgresql')");

    assertThat(lines("SELECT id, n, v FROM t ORDER BY id")).containsExactly("1|1|sql", "2|2|content", "3|3|cypher",
        "4|4|java", "5|5|postgresql");
    // GENERATED ALWAYS is a rule of this language: another one writes the value it is given
    database.transaction(() -> database.command("sql", "INSERT INTO t SET id = 100, n = 100, v = 'given'").close());
    assertThat(numbers("INSERT INTO t (v) VALUES ('next') RETURNING id")).containsExactly(6L);
  }

  @Test
  void aRollbackLeavesAGapAndAReopenGoesOn() {
    run("CREATE TABLE t (id serial PRIMARY KEY, v text)");
    run("BEGIN");
    assertThat(numbers("INSERT INTO t (v) VALUES ('gone') RETURNING id")).containsExactly(1L);
    run("ROLLBACK");
    // a transaction of the caller, which the counter does not join
    database.begin();
    run("INSERT INTO t (v) VALUES ('gone too')");
    database.rollback();
    assertThat(numbers("INSERT INTO t (v) VALUES ('kept') RETURNING id")).containsExactly(3L);

    reopenDatabase();

    assertThat(numbers("INSERT INTO t (v) VALUES ('after') RETURNING id")).containsExactly(4L);
  }

  @Test
  void aValueGivenByAStatementDoesNotMoveTheCounter() {
    run("CREATE TABLE t (id serial PRIMARY KEY, v text)");
    run("INSERT INTO t (id, v) VALUES (1, 'given')");
    assertState("INSERT INTO t (v) VALUES ('meets it')", "23505");
    assertThat(numbers("INSERT INTO t (v) VALUES ('goes on') RETURNING id")).containsExactly(2L);
  }

  @ParameterizedTest
  @CsvSource(delimiter = ';', quoteCharacter = '"', value = {
      "INSERT INTO t (n) VALUES (5); 428C9",
      "INSERT INTO t (n) VALUES (NULL); 428C9",
      "INSERT INTO t (n) SELECT id FROM t; 428C9",
      "UPDATE t SET n = 5; 428C9",
      "CREATE TABLE e (a text GENERATED ALWAYS AS IDENTITY); 22023",
      "CREATE TABLE e (a serial DEFAULT 1); 42601",
      "CREATE TABLE e (a serial NULL); 42601",
      "CREATE TABLE e (a int NULL GENERATED ALWAYS AS IDENTITY); 42601",
      "CREATE TABLE e (a int DEFAULT 1 GENERATED ALWAYS AS IDENTITY); 42601",
      "CREATE TABLE e (a int GENERATED ALWAYS AS IDENTITY DEFAULT 1); 42601",
      "CREATE TABLE e (a serial GENERATED ALWAYS AS IDENTITY); 42601",
      "CREATE TABLE e (a int GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY); 42601",
      "CREATE TABLE e (a int GENERATED BY DEFAULT AS (1) STORED); 42601",
      "CREATE TABLE e (a int GENERATED ALWAYS AS IDENTITY (INCREMENT BY -1)); 0A000",
      "CREATE TABLE e (a int GENERATED ALWAYS AS IDENTITY (MAXVALUE 10)); 0A000",
      "CREATE TABLE _postgresql_sequences (a int); 0A000" })
  void eachRefusalKeepsItsState(final String statement, final String sqlState) {
    run("CREATE TABLE t (id int PRIMARY KEY, n int GENERATED ALWAYS AS IDENTITY)");
    assertState(statement, sqlState);
    assertThat(database.getSchema().existsType("e")).isFalse();
  }

  @Test
  void theCountersAreNoTableAndATableMadeAgainStartsAtOne() {
    run("CREATE TABLE t (id serial PRIMARY KEY, v text)");
    run("INSERT INTO t (v) VALUES ('a'), ('b')");

    assertThat(lines("SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' ORDER BY table_name"))
        .containsExactly("t");
    assertState("SELECT * FROM _postgresql_sequences", "42P01");

    database.command("sql", "DROP TYPE t UNSAFE").close();
    run("CREATE TABLE t (id serial PRIMARY KEY, v text)");

    assertThat(numbers("INSERT INTO t (v) VALUES ('a') RETURNING id")).containsExactly(1L);
  }

  @Test
  void anEdgeTableCountsItsKeyToo() {
    run("CREATE TABLE person (id serial PRIMARY KEY, name text)");
    run("CREATE TABLE knows (id serial PRIMARY KEY, source_id text NOT NULL REFERENCES person (rid) ON DELETE CASCADE,"
        + " target_id text NOT NULL REFERENCES person (rid) ON DELETE CASCADE)");
    run("INSERT INTO person (name) VALUES ('Ada'), ('Bob')");
    run("INSERT INTO knows (source_id, target_id) SELECT a.rid, b.rid FROM person a, person b WHERE a.id = 1 AND b.id = 2");

    assertThat(numbers("SELECT id FROM knows")).containsExactly(1L);
  }

  /** Several sessions insert at once: no value is given twice, and the counter fails none of them. */
  @Test
  void concurrentInsertsTakeDifferentNumbers() throws InterruptedException {
    run("CREATE TABLE t (id serial PRIMARY KEY, v text)");
    final int sessions = 4;
    final int rows = 100;
    final Set<Long> taken = ConcurrentHashMap.newKeySet();
    final List<Throwable> failures = new CopyOnWriteArrayList<>();
    final List<Thread> threads = new ArrayList<>();
    for (int s = 0; s < sessions; s++) {
      final int session = s;
      threads.add(new Thread(() -> {
        try {
          for (int i = 0; i < rows; i++)
            insertAgainOnConflict("s" + session);
          // the counter alone, with nothing to run again: not one of these may fail
          for (int i = 0; i < rows; i++)
            assertThat(taken.add(Sequences.next(database, key()))).isTrue();
        } catch (final Throwable e) {
          failures.add(e);
        }
      }));
    }
    threads.forEach(Thread::start);
    for (final Thread thread : threads)
      thread.join();

    assertThat(failures).isEmpty();
    final List<Long> ids = numbers("SELECT id FROM t");
    assertThat(ids).hasSize(sessions * rows).doesNotHaveDuplicates().allMatch(id -> id > 0);
    assertThat(taken).hasSize(sessions * rows);
  }

  /** An insert that meets another commit on the pages of the table is run again, as a client of the language does. */
  private void insertAgainOnConflict(final String value) {
    for (; ; )
      try {
        database.command("postgresql", "INSERT INTO t (v) VALUES ($1)", value).close();
        return;
      } catch (final RuntimeException e) {
        if (!"40001".equals(PostgreSQLErrors.sqlState(e)))
          throw e;
      }
  }

  /** The key of the counter of {@code t.id}. */
  private String key() {
    return Sequences.keyOf(database.getSchema().getType("t").getProperty("id").getDefaultValueDefinition());
  }

  private void run(final String statement) {
    database.command("postgresql", statement).close();
  }

  private List<Result> rows(final String statement) {
    final List<Result> rows = new ArrayList<>();
    try (final ResultSet resultSet = database.command("postgresql", statement)) {
      while (resultSet.hasNext())
        rows.add(resultSet.next());
    }
    return rows;
  }

  /** The values of the column {@code id} of the answer, sorted as the statement answers them. */
  private List<Long> numbers(final String statement) {
    return rows(statement).stream().map(row -> row.<Number>getProperty("id").longValue()).toList();
  }

  private List<String> lines(final String statement) {
    final List<String> columns = ((PostgreSQLQueryEngine) ((com.arcadedb.database.DatabaseInternal) database).getQueryEngine(
        "postgresql")).describe(statement).stream().map(column -> column.name()).toList();
    return rows(statement).stream()
        .map(row -> String.join("|", columns.stream().map(column -> String.valueOf(row.<Object>getProperty(column))).toList()))
        .toList();
  }

  private void assertState(final String statement, final String sqlState) {
    assertThatThrownBy(() -> run(statement)).as(statement)
        .satisfies(e -> assertThat(PostgreSQLErrors.sqlState(e)).as(e.getMessage()).isEqualTo(sqlState));
  }
}
