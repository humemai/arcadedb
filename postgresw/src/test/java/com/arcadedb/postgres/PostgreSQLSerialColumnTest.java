/**
 * {@code serial} and identity columns of the {@code postgresql} language against PostgreSQL 18 (fork issue #221), over JDBC and
 * with psycopg and SQLAlchemy.
 */
class PostgreSQLSerialColumnTest extends PostgreSQLSideBySideTestBase {
  private static final List<String> TABLES = List.of(
      "CREATE TABLE p01 (id serial PRIMARY KEY, v text)",
      "CREATE TABLE p02 (id bigserial PRIMARY KEY, v text)",
      "CREATE TABLE p03 (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v text)",
      "CREATE TABLE p04 (id int GENERATED BY DEFAULT AS IDENTITY, v text)",
      "CREATE TABLE p05 (id smallserial, n SERIAL NOT NULL, s smallint generated always as identity, v text)",
      "CREATE TABLE \"Users\" (id SERIAL, name varchar NOT NULL, PRIMARY KEY (id))",
      "CREATE TABLE p06 (id integer GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 1 START WITH 1) PRIMARY KEY, v text)");

  private static final String COLUMNS = "SELECT table_name, column_name, column_default, is_nullable, data_type, is_identity,"
      + " identity_generation, identity_start, identity_increment, identity_maximum, identity_minimum, identity_cycle"
      + " FROM information_schema.columns WHERE table_name IN ('p01', 'p02', 'p03', 'p04', 'p05', 'p06', 'Users')"
      + " ORDER BY table_name, ordinal_position";

  private static final String SCRIPT = """
      import sys
      import psycopg
      import sqlalchemy as sa
      from sqlalchemy import orm

      CONNINFO = sys.argv[1]

      class Base(orm.DeclarativeBase):
          pass

      class User(Base):
          __tablename__ = "orm_user"
          id: orm.Mapped[int] = orm.mapped_column(primary_key=True)
          name: orm.Mapped[str] = orm.mapped_column(sa.String)

      class Event(Base):
          __tablename__ = "orm_event"
          id: orm.Mapped[int] = orm.mapped_column(sa.BigInteger, sa.Identity(always=True), primary_key=True)
          user_id: orm.Mapped[int] = orm.mapped_column(sa.Integer)

      engine = sa.create_engine("postgresql+psycopg://", creator=lambda: psycopg.connect(CONNINFO))
      Base.metadata.create_all(engine.execution_options(isolation_level="AUTOCOMMIT"))
      with orm.Session(engine) as session:
          users = [User(name="Ada"), User(name="Bo")]
          session.add_all(users)
          session.flush()
          print([user.id for user in users])
          events = [Event(user_id=1), Event(user_id=2), Event(user_id=1)]
          session.add_all(events)
          session.commit()
          print([event.id for event in events])
          print(session.execute(sa.select(User.id, User.name, Event.id).join(Event, Event.user_id == User.id)
                                .order_by(Event.id)).all())

      reflected = sa.Table("orm_user", sa.MetaData(), autoload_with=engine)
      column = reflected.c.id
      print(column.autoincrement, column.server_default.arg.text)
      with engine.begin() as connection:
          print(connection.execute(reflected.insert().values(name="Cy")).inserted_primary_key)

      with psycopg.connect(CONNINFO) as conn:
          cursor = conn.cursor()
          cursor.execute("INSERT INTO orm_user (name) VALUES (%s) RETURNING id", ("Di",))
          print(cursor.fetchone()[0])
          conn.rollback()
          cursor.executemany("INSERT INTO orm_user (name) VALUES (%s)", [("Ed",), ("Flo",)])
          conn.commit()
          cursor.execute("SELECT id, name FROM orm_user ORDER BY id")
          print(cursor.fetchall())
          try:
              cursor.execute("INSERT INTO orm_event (id, user_id) VALUES (%s, %s)", (50, 1))
          except psycopg.Error as e:
              print(e.sqlstate, e.diag.message_primary)
      """;

  @Test
  void generatedKeysAnswerAsOnPostgreSql() throws Exception {
    try (final GenericContainer<?> container = startPostgres()) {
      try (final Connection postgres = postgres(container, ""); final Connection arcade = arcade("")) {
        for (final String table : TABLES)
          both(postgres, arcade, table);
        assertThat(failures).as(String.join("\n", failures)).isEmpty();
        sameValues(postgres, arcade, COLUMNS);

        for (final String write : List.of("INSERT INTO p01 (v) VALUES ('a'), ('b')",
            "INSERT INTO p01 (id, v) VALUES (DEFAULT, 'c')", "INSERT INTO p01 VALUES (DEFAULT, 'd')",
            "INSERT INTO p02 (v) SELECT v FROM p01 ORDER BY id", "INSERT INTO p03 (v) VALUES ('x'), ('y')",
            "INSERT INTO p04 (id, v) VALUES (10, 'ten')", "INSERT INTO p04 (v) VALUES ('one')",
            "INSERT INTO p05 (v) VALUES ('a'), ('b')", "INSERT INTO \"Users\" (name) VALUES ('Ada'), ('Bo')",
            "UPDATE p01 SET id = DEFAULT WHERE v = 'a'", "INSERT INTO p06 (id, v) VALUES (1, 'given')"))
          both(postgres, arcade, write);
        // a value that a statement gave meets the counter, which then goes on
        sameError(postgres, arcade, "INSERT INTO p06 (v) VALUES ('meets')", "23505");
        for (final String query : List.of("INSERT INTO p06 (v) VALUES ('goes on') RETURNING id, v",
            "INSERT INTO p01 (v) VALUES ('e') RETURNING *", "INSERT INTO p03 (id, v) VALUES (DEFAULT, 'z') RETURNING id",
            "SELECT * FROM p01 ORDER BY id", "SELECT * FROM p02 ORDER BY id", "SELECT * FROM p03 ORDER BY id",
            "SELECT * FROM p04 ORDER BY id", "SELECT * FROM p05 ORDER BY id", "SELECT * FROM \"Users\" ORDER BY id",
            "SELECT * FROM p06 ORDER BY id"))
          same(postgres, arcade, query);

        sameError(postgres, arcade, "INSERT INTO p03 (id, v) VALUES (5, 'z')", "428C9");
        sameError(postgres, arcade, "UPDATE p03 SET id = 7", "428C9");
        sameError(postgres, arcade, "INSERT INTO p01 (id, v) VALUES (NULL, 'n')", "23502");
        sameError(postgres, arcade, "INSERT INTO p01 (id, v) VALUES (2, 'taken')", "23505");
        sameError(postgres, arcade, "CREATE TABLE e (a text GENERATED ALWAYS AS IDENTITY)", "22023");
        sameError(postgres, arcade, "CREATE TABLE e (a serial DEFAULT 1)", "42601");
        sameError(postgres, arcade, "CREATE TABLE e (a serial NULL)", "42601");
        sameError(postgres, arcade, "CREATE TABLE e (a int DEFAULT 1 GENERATED ALWAYS AS IDENTITY)", "42601");
        sameError(postgres, arcade,
            "CREATE TABLE e (a int GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY)", "42601");
        sameError(postgres, arcade, "CREATE TABLE e (a int GENERATED BY DEFAULT AS (1) STORED)", "42601");
        refused(arcade, "CREATE TABLE e (a int GENERATED ALWAYS AS IDENTITY (START WITH 100))", "An identity option");

        assertThat(failures).as(String.join("\n", failures)).isEmpty();
      }
      python(container, SCRIPT);
    }
  }

  /** Two sessions insert at once into one table: every row is written, and every number is given once. */
  @Test
  void twoSessionsThatInsertAtOnceTakeDifferentNumbers() throws Exception {
    try (final GenericContainer<?> container = startPostgres()) {
      try (final Connection pgFirst = postgres(container, ""); final Connection pgSecond = postgres(container, "");
          final Connection first = arcade(""); final Connection second = arcade("")) {
        for (final Connection connection : List.of(pgFirst, first))
          run(connection, "CREATE TABLE busy (id serial PRIMARY KEY, v text)");

        insertAtOnce("PostgreSQL", pgFirst, pgSecond);
        insertAtOnce("ArcadeDB", first, second);
      }
    }
  }

  private static void insertAtOnce(final String server, final Connection first, final Connection second) throws Exception {
    final int rows = 200;
    final Set<Long> ids = ConcurrentHashMap.newKeySet();
    final AtomicInteger again = new AtomicInteger();
    final List<Callable<Void>> sessions = new ArrayList<>();
    for (final Connection connection : List.of(first, second))
      sessions.add(() -> {
        try (final PreparedStatement insert = connection.prepareStatement("INSERT INTO busy (v) VALUES (?) RETURNING id")) {
          for (int i = 0; i < rows; i++) {
            insert.setString(1, "row " + i);
            for (; ; )
              try (final ResultSet written = insert.executeQuery()) {
                assertThat(written.next()).isTrue();
                assertThat(ids.add(written.getLong(1))).as("a number given twice").isTrue();
                break;
              } catch (final SQLException e) {
                // two commits on the pages of one table: the later one runs again (fork issue #239)
                if (!"40001".equals(e.getSQLState()))
                  throw e;
                again.incrementAndGet();
              }
          }
        }
        return null;
      });
    final ExecutorService pool = Executors.newFixedThreadPool(sessions.size());
    try {
      for (final Future<Void> session : pool.invokeAll(sessions))
        session.get();
    } finally {
      pool.shutdownNow();
    }
    System.out.println(server + ": " + 2 * rows + " rows from two sessions, " + again.get() + " inserts run again after 40001");
    assertThat(ids).hasSize(2 * rows).allMatch(id -> id > 0);
    assertThat(answer(first, "SELECT count(*) AS rows FROM busy", false)).contains(Integer.toString(2 * rows));
  }
}
