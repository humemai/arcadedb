package com.arcadedb.postgres;

import com.arcadedb.database.Database;
import com.arcadedb.exception.ValidationException;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.GenericContainer;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * The {@code uuid} type of the {@code postgresql} language and {@code DEFAULT gen_random_uuid()} against PostgreSQL 18 (fork
 * issues #225 and #224), over JDBC, in text and in binary, and with psycopg and SQLAlchemy.
 */
class PostgreSQLUuidTest extends PostgreSQLSideBySideTestBase {
  private static final String ADA = "11111111-1111-1111-1111-111111111111";

  private static final List<String> TABLES = List.of(
      "CREATE TABLE users (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), email text NOT NULL UNIQUE,"
          + " is_active boolean NOT NULL DEFAULT true, created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP)",
      "CREATE TABLE p28 (id int PRIMARY KEY, u uuid)",
      "CREATE TABLE auto3 (id text PRIMARY KEY DEFAULT gen_random_uuid(), name text)",
      "CREATE TABLE auto4 (id varchar PRIMARY KEY DEFAULT gen_random_uuid()::varchar, name text DEFAULT gen_random_uuid()::text)",
      "CREATE TABLE fixed (id int PRIMARY KEY, u uuid DEFAULT '{A3BB189E-8BF9-3888-9912-ACE4E6543002}',"
          + " v uuid DEFAULT 'a3bb189e8bf938889912ace4e6543002'::uuid)",
      "CREATE TABLE orders (id bigserial PRIMARY KEY, user_id uuid NOT NULL REFERENCES users(id), note text)",
      "CREATE TABLE audit_log (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id uuid, action text NOT NULL,"
          + " payload jsonb, at timestamp NOT NULL DEFAULT now())",
      "CREATE INDEX audit_user ON audit_log (user_id)");

  private static final String COLUMNS = "SELECT table_name, column_name, column_default, is_nullable, data_type, udt_name,"
      + " character_maximum_length FROM information_schema.columns WHERE table_name IN ('users', 'p28', 'auto3', 'auto4',"
      + " 'fixed', 'orders', 'audit_log') ORDER BY table_name, ordinal_position";

  private static final String SCRIPT = """
      import sys
      import uuid
      import psycopg
      import sqlalchemy as sa
      from sqlalchemy import orm

      CONNINFO = sys.argv[1]

      class Base(orm.DeclarativeBase):
          pass

      class Doc(Base):
          __tablename__ = "orm_doc"
          id: orm.Mapped[uuid.UUID] = orm.mapped_column(sa.Uuid, primary_key=True, default=lambda: uuid.UUID(int=7))
          title: orm.Mapped[str] = orm.mapped_column(sa.String)

      engine = sa.create_engine("postgresql+psycopg://", creator=lambda: psycopg.connect(CONNINFO))
      Base.metadata.create_all(engine.execution_options(isolation_level="AUTOCOMMIT"))
      with orm.Session(engine) as session:
          session.add_all([Doc(title="first"), Doc(id=uuid.UUID(int=8), title="second")])
          session.commit()
          print(session.get(Doc, uuid.UUID(int=8)).title)
          print(session.execute(sa.select(Doc.id, Doc.title).order_by(Doc.id)).all())
      reflected = sa.Table("orm_doc", sa.MetaData(), autoload_with=engine)
      print(type(reflected.c.id.type).__name__)

      with psycopg.connect(CONNINFO) as conn:
          for binary in (False, True):
              cursor = conn.cursor(binary=binary)
              cursor.execute("SELECT id, title FROM orm_doc WHERE id = %s", (uuid.UUID(int=7),))
              print(cursor.fetchall())
              cursor.execute("SELECT id FROM orm_doc WHERE id = %s", (str(uuid.UUID(int=8)),))
              print(cursor.fetchall())
          cursor = conn.cursor()
          try:
              cursor.execute("SELECT id FROM orm_doc WHERE id = %s", ("not a uuid",))
          except psycopg.Error as e:
              print(e.sqlstate)
      """;

  @Test
  void uuidAnswersAsOnPostgreSql() throws Exception {
    try (final GenericContainer<?> container = startPostgres()) {
      try (final Connection postgres = postgres(container, ""); final Connection arcade = arcade("")) {
        for (final String table : TABLES)
          both(postgres, arcade, table);
        assertThat(failures).as(String.join("\n", failures)).isEmpty();
        sameValues(postgres, arcade, COLUMNS);

        for (final String write : List.of(
            "INSERT INTO users (id, email) VALUES ('" + ADA + "', 'a@x'), ('{22222222222222222222222222222222}', 'b@x')",
            "INSERT INTO users (email) VALUES ('c@x'), ('d@x')",
            "INSERT INTO p28 VALUES (1, 'A3BB189E-8BF9-3888-9912-ACE4E6543002'), (2, NULL),"
                + " (3, '00000000-0000-0000-0000-000000000000')",
            "INSERT INTO p28 VALUES (4, 'a3bb-189e-8bf9-3888-9912-ace4-e654-3003')", "INSERT INTO fixed (id) VALUES (1)",
            "INSERT INTO auto3 (name) VALUES ('a'), ('b')", "INSERT INTO auto4 DEFAULT VALUES",
            "INSERT INTO orders (user_id) VALUES ('" + ADA + "')",
            "INSERT INTO audit_log (user_id, action) SELECT id, 'seen' FROM users WHERE email = 'a@x'",
            "UPDATE p28 SET u = 'ffffffff-ffff-ffff-ffff-ffffffffffff' WHERE id = 2"))
          both(postgres, arcade, write);

        for (final String query : List.of("SELECT id, u FROM p28 ORDER BY u", "SELECT id FROM p28 ORDER BY u DESC",
            "SELECT id, u FROM p28 WHERE u = 'a3bb189e-8bf9-3888-9912-ace4e6543002'",
            "SELECT id FROM p28 WHERE u > '00000000-0000-0000-0000-000000000000' ORDER BY id",
            "SELECT id FROM p28 WHERE u IN ('a3bb189e-8bf9-3888-9912-ace4e6543002', 'ffffffffffffffffffffffffffffffff')"
                + " ORDER BY id",
            "SELECT u::text AS t, u::varchar AS v, 'x' || u::text AS w FROM fixed", "SELECT * FROM fixed",
            "SELECT 'a3bb189e-8bf9-3888-9912-ace4e6543002'::uuid", "SELECT count(DISTINCT u), count(u) FROM p28",
            "SELECT u, count(*) FROM p28 GROUP BY u ORDER BY u",
            "SELECT o.id, c.email FROM orders o JOIN users c ON c.id = o.user_id ORDER BY o.id",
            "SELECT a.id, c.email, a.user_id FROM audit_log a LEFT JOIN users c ON c.id = a.user_id ORDER BY a.id",
            "SELECT email FROM users WHERE id = '" + ADA + "'", "SELECT count(*), count(DISTINCT id) FROM users",
            "SELECT length(id), name FROM auto3 ORDER BY name", "SELECT length(id), length(name) FROM auto4",
            "SELECT a.u = b.u AS same, a.u < b.v AS lower FROM fixed a, fixed b"))
          sameValues(postgres, arcade, query);
        same(postgres, arcade, "SELECT u FROM p28 WHERE id = 1");

        // a value bound as a uuid and read back as one, in text and in binary
        for (final String parameters : List.of("", "?prepareThreshold=-1")) {
          try (final Connection first = postgres(container, parameters); final Connection second = arcade(parameters)) {
            for (int run = 0; run < 3; run++)
              compare("a bound uuid " + parameters, bound(first), bound(second));
          }
        }

        for (final String[] error : new String[][] { { "INSERT INTO p28 VALUES (9, 'nope')", "22P02" },
            { "SELECT * FROM p28 WHERE u = 'nope'", "22P02" },
            { "SELECT ' a3bb189e-8bf9-3888-9912-ace4e6543002'::uuid", "22P02" },
            { "SELECT * FROM p28 WHERE u = id::text", "42883" }, { "SELECT max(u) FROM p28", "42883" },
            { "SELECT length(u) FROM p28", "42883" }, { "SELECT u::int FROM p28", "42846" },
            { "INSERT INTO p28 VALUES (10, 1)", "42804" }, { "INSERT INTO p28 SELECT 11, name FROM auto3", "42804" },
            { "CREATE TABLE e (a uuid DEFAULT 'x')", "22P02" },
            { "CREATE TABLE e (a uuid DEFAULT gen_random_uuid()::text)", "42804" },
            { "CREATE TABLE e (a int DEFAULT gen_random_uuid())", "42804" },
            { "CREATE TABLE e (a text REFERENCES users(id))", "42804" },
            { "INSERT INTO orders (user_id) VALUES ('33333333-3333-3333-3333-333333333333')", "23503" },
            { "INSERT INTO users (id, email) VALUES ('11111111111111111111111111111111', 'again@x')", "23505" } })
          sameError(postgres, arcade, error[0], error[1]);

        // another language writes the canonical text, and any other is refused by the schema
        final Database database = getServerDatabase(0, getDatabaseName());
        database.transaction(
            () -> database.command("sql", "INSERT INTO p28 SET id = 20, u = '44444444-4444-4444-4444-444444444444'"));
        database.transaction(
            () -> database.command("opencypher", "CREATE (:p28 {id: 21, u: '55555555-5555-5555-5555-555555555555'})"));
        for (final String refused : List.of("INSERT INTO p28 SET id = 22, u = 'nope'",
            "UPDATE p28 SET u = 'A3BB189E-8BF9-3888-9912-ACE4E6543002' WHERE id = 20"))
          assertThatThrownBy(() -> database.transaction(() -> database.command("sql", refused)))
              .isInstanceOf(ValidationException.class);
        run(postgres, "INSERT INTO p28 VALUES (20, '44444444-4444-4444-4444-444444444444'),"
            + " (21, '55555555-5555-5555-5555-555555555555')");
        sameValues(postgres, arcade, "SELECT * FROM p28 ORDER BY id");

        assertThat(failures).as(String.join("\n", failures)).isEmpty();
      }
      python(container, SCRIPT);
    }
  }

  private static String bound(final Connection connection) throws SQLException {
    final StringBuilder out = new StringBuilder();
    try (final PreparedStatement select = connection.prepareStatement(
        "SELECT id, email FROM users WHERE id = ? ORDER BY email")) {
      select.setObject(1, UUID.fromString(ADA));
      try (final ResultSet rows = select.executeQuery()) {
        while (rows.next())
          out.append("    ").append(rows.getObject(1).getClass().getSimpleName()).append(' ').append(rows.getObject(1, UUID.class))
              .append(' ').append(rows.getString(2)).append('\n');
      }
    }
    return out.toString();
  }
}
